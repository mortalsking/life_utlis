-- ----------------------------------------------------------------------------
-- 1. USER DATA TABLE (Main App Cloud Sync)
-- ----------------------------------------------------------------------------
create table if not exists public.user_data (
  id uuid references auth.users not null primary key,
  data jsonb not null default '{}'::jsonb,
  updated_at timestamp with time zone default timezone('utc'::text, now()) not null
);

alter table public.user_data enable row level security;

-- Policies for user_data: Strictly isolated per user
drop policy if exists "Users can read their own data" on public.user_data;
create policy "Users can read their own data"
  on public.user_data for select
  using (auth.uid() = id);

drop policy if exists "Users can upsert their own data" on public.user_data;
create policy "Users can upsert their own data"
  on public.user_data for insert
  with check (auth.uid() = id);

drop policy if exists "Users can update their own data" on public.user_data;
create policy "Users can update their own data"
  on public.user_data for update
  using (auth.uid() = id);

-- ----------------------------------------------------------------------------
-- 2. FORUM & COMMUNITY FEEDBACK TABLE (Secured & Hardened)
-- ----------------------------------------------------------------------------
create table if not exists public.feedback (
  id bigint generated by default as identity primary key,
  created_at timestamp with time zone default timezone('utc'::text, now()) not null,
  user_id uuid references auth.users(id) on delete set null,
  user_name text not null default 'Anonymous' check (length(user_name) <= 100),
  content text not null check (length(content) > 0 and length(content) <= 1000),
  category text not null default 'General' check (length(category) <= 50),
  device text default 'web' check (length(device) <= 30),
  likes integer not null default 0 check (likes >= 0)
);

-- Index for ordering by recency
create index if not exists idx_feedback_created_at on public.feedback (created_at desc);

-- Enable Row Level Security (RLS)
alter table public.feedback enable row level security;

-- Drop prior permissive or insecure policies
drop policy if exists "Anyone can view feedback" on public.feedback;
drop policy if exists "Anyone can read feedback" on public.feedback;
drop policy if exists "Anyone can insert feedback" on public.feedback;
drop policy if exists "Anyone can like feedback" on public.feedback;
drop policy if exists "Authors can update their own feedback" on public.feedback;
drop policy if exists "Authors can delete their own feedback" on public.feedback;

-- Policy 1: Anyone (both authenticated users and guests) can read feedback
create policy "Anyone can view feedback"
  on public.feedback for select
  using (true);

-- Policy 2: Anyone (both authenticated users and guests) can insert feedback
create policy "Anyone can insert feedback"
  on public.feedback for insert
  with check (true);

-- Policy 3: Only post authors can update their own posts (prevents content defacement)
create policy "Authors can update their own feedback"
  on public.feedback for update
  using (auth.uid() is not null and auth.uid() = user_id)
  with check (auth.uid() is not null and auth.uid() = user_id);

-- Policy 4: Only post authors can delete their own posts
create policy "Authors can delete their own feedback"
  on public.feedback for delete
  using (auth.uid() is not null and auth.uid() = user_id);

-- ----------------------------------------------------------------------------
-- 3. SECURE STORED PROCEDURE FOR FEEDBACK LIKES (Prevents Defacement)
-- ----------------------------------------------------------------------------
-- Allows atomic like / unlike increments without opening full row UPDATE to anon.
create or replace function public.increment_feedback_likes(row_id bigint, delta int default 1)
returns integer
language plpgsql
security definer
set search_path = public
as $$
declare
  new_likes integer;
begin
  update public.feedback
  set likes = greatest(0, likes + delta)
  where id = row_id
  returning likes into new_likes;
  
  return coalesce(new_likes, 0);
end;
$$;

-- Grant execution to all clients (both anon guest and authenticated)
grant execute on function public.increment_feedback_likes(bigint, int) to anon, authenticated;

-- ----------------------------------------------------------------------------
-- 4. ENABLE REALTIME
-- ----------------------------------------------------------------------------
do $$
begin
  if not exists (
    select 1 from pg_publication_tables 
    where pubname = 'supabase_realtime' and tablename = 'feedback'
  ) then
    alter publication supabase_realtime add table public.feedback;
  end if;
end $$;
